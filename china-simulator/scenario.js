function conditionMatches(condition = {}, state) {
  if (!condition.flag) return true;
  const value = state.flags[condition.flag];
  if ("equals" in condition && value !== condition.equals) return false;
  if ("gte" in condition && Number(value ?? -Infinity) < condition.gte) return false;
  if ("lte" in condition && Number(value ?? Infinity) > condition.lte) return false;
  return true;
}

export function resolveScene(scenario, state, sceneId = state.sceneId) {
  const scene = structuredClone(scenario.scenes[sceneId]);
  const variants = scenario.branches?.[sceneId] || [];
  const variant = variants.find((item) => !item.default && conditionMatches(item.when, state))
    || variants.find((item) => item.default);
  if (!variant) return scene;
  const { when, default: isDefault, ...overrides } = variant;
  return { ...scene, ...overrides };
}

